<script>
document.addEventListener("DOMContentLoaded", function () {

    const track = document.querySelector(".catalogo-servicios-track");
    const botonAnterior = document.querySelector(
        ".catalogo-flecha-anterior"
    );
    const botonSiguiente = document.querySelector(
        ".catalogo-flecha-siguiente"
    );
    const barraProgreso = document.querySelector(
        ".catalogo-progreso-barra"
    );

    if (
        !track ||
        !botonAnterior ||
        !botonSiguiente ||
        !barraProgreso
    ) {
        return;
    }

    function obtenerDesplazamiento() {

        const primeraTarjeta = track.querySelector(
            ".catalogo-servicio-card"
        );

        if (!primeraTarjeta) {
            return 320;
        }

        const estilosTrack = window.getComputedStyle(track);
        const espacio = parseFloat(estilosTrack.columnGap) || 22;

        return primeraTarjeta.offsetWidth + espacio;
    }

    function actualizarControles() {

        const maxScroll = track.scrollWidth - track.clientWidth;
        const scrollActual = track.scrollLeft;

        botonAnterior.disabled = scrollActual <= 5;
        botonSiguiente.disabled = scrollActual >= maxScroll - 5;

        if (maxScroll <= 0) {
            barraProgreso.style.width = "100%";
            barraProgreso.style.transform = "translateX(0)";
            return;
        }

        const porcentajeVisible =
            track.clientWidth / track.scrollWidth;

        const anchoBarra = Math.max(
            22,
            porcentajeVisible * 100
        );

        const progreso =
            Math.min(1, Math.max(0, scrollActual / maxScroll));

        const desplazamiento =
            progreso * (100 - anchoBarra);

        barraProgreso.style.width = `${anchoBarra}%`;
        barraProgreso.style.transform =
            `translateX(${desplazamiento}%)`;
    }

    botonSiguiente.addEventListener("click", function () {

        track.scrollBy({
            left: obtenerDesplazamiento(),
            behavior: "smooth"
        });

    });

    botonAnterior.addEventListener("click", function () {

        track.scrollBy({
            left: -obtenerDesplazamiento(),
            behavior: "smooth"
        });

    });

    track.addEventListener(
        "scroll",
        actualizarControles,
        { passive: true }
    );

    window.addEventListener(
        "resize",
        actualizarControles
    );

    actualizarControles();

});
</script>

