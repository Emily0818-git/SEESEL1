                "Mantenimiento correctivo realizado por personal SEESEL",
            color: "#f97316",
            rgb: "249, 115, 22",
            tema: "tema-correctivo",
            beneficios: [
                "Localización precisa de fallas",
                "Cambios de equipos eléctricos",
                "Respuesta técnica especializada",
                "Pruebas posteriores a la reparación"
            ]
        }

    };

    function crearBeneficios(elementos) {

        beneficios.innerHTML = "";

        elementos.forEach(function (texto) {

            const item = document.createElement("li");

            item.innerHTML = `
                <i class="fa-solid fa-circle-check"></i>
                ${texto}
            `;

            beneficios.appendChild(item);

        });

    }

    function cambiarMantenimiento(tipo) {

        const datos = informacion[tipo];

        if (!datos) {
            return;
        }

        tabs.forEach(function (tab) {

            const activo =
                tab.dataset.mantenimiento === tipo;

            tab.classList.toggle("activo", activo);
            tab.setAttribute(
                "aria-selected",
                activo ? "true" : "false"
            );

        });

        seccion.classList.remove(
            "tema-preventivo",
            "tema-predictivo",
            "tema-correctivo"
        );

        seccion.classList.add(datos.tema);

        seccion.style.setProperty(
            "--mantenimiento-color",
            datos.color
        );

        seccion.style.setProperty(
            "--mantenimiento-color-rgb",
            datos.rgb
        );

        panel.classList.remove("animando");

        void panel.offsetWidth;

        panel.classList.add("animando");

        imagen.style.opacity = "0";

        setTimeout(function () {

            categoria.textContent = datos.categoria;
            titulo.textContent = datos.titulo;
            descripcion.textContent = datos.descripcion;

            crearBeneficios(datos.beneficios);

            imagen.src = datos.imagen;
            imagen.alt = datos.alt;

            numeroGrande.textContent = datos.numero;

            if (numeroIndicador) {
                numeroIndicador.textContent = datos.numero;
            }

            if (tituloIndicador) {
                tituloIndicador.textContent = datos.nombre;
            }

            imagen.onload = function () {
                imagen.style.opacity = "1";
            };

            setTimeout(function () {
                imagen.style.opacity = "1";
            }, 250);

        }, 180);

    }

    tabs.forEach(function (tab) {

        tab.addEventListener("click", function () {

            cambiarMantenimiento(
                this.dataset.mantenimiento
            );

        });

    });

    seccion.classList.add("tema-preventivo");

});
</script>