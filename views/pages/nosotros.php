<script>
document.addEventListener("DOMContentLoaded", function () {

    const itemsHistoria = document.querySelectorAll(".historia-item");

    if (!itemsHistoria.length) {
        return;
    }

    const observerHistoria = new IntersectionObserver(
        function (entries, observer) {

            entries.forEach(function (entry) {

                if (entry.isIntersecting) {
                    entry.target.classList.add("historia-visible");
                    observer.unobserve(entry.target);
                }

            });

        },
        {
            threshold: 0.18
        }
    );

    itemsHistoria.forEach(function (item) {
        observerHistoria.observe(item);
    });

});
</script>