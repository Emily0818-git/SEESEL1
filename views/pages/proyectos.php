<script>
document.addEventListener("DOMContentLoaded", function () {

    const modalImagen = document.getElementById("modalImagen");
    const imagenGrande = document.getElementById("imagenGrande");
    const cerrarImagen = document.getElementById("cerrarImagen");
    const imagenesAbrir = document.querySelectorAll(".abrir-imagen");

    if (!modalImagen || !imagenGrande || !cerrarImagen) {
        console.error("No se encontraron los elementos del modal de imagen.");
        return;
    }

    imagenesAbrir.forEach(function (contenedor) {

        contenedor.addEventListener("click", function () {

            const rutaImagen = contenedor.dataset.imagen;
            const textoAlternativo = contenedor.dataset.alt || "Imagen ampliada";

            if (!rutaImagen) {
                console.error("La tarjeta no tiene el atributo data-imagen.");
                return;
            }

            imagenGrande.src = rutaImagen;
            imagenGrande.alt = textoAlternativo;

            modalImagen.classList.add("activo");
            document.body.classList.add("modal-abierto");
        });

    });

    function cerrarModalImagen() {
        modalImagen.classList.remove("activo");
        document.body.classList.remove("modal-abierto");

        setTimeout(function () {
            imagenGrande.src = "";
        }, 300);
    }

    cerrarImagen.addEventListener("click", cerrarModalImagen);

    modalImagen.addEventListener("click", function (evento) {
        if (evento.target === modalImagen) {
            cerrarModalImagen();
        }
    });

    document.addEventListener("keydown", function (evento) {
        if (
            evento.key === "Escape" &&
            modalImagen.classList.contains("activo")
        ) {
            cerrarModalImagen();
        }
    });

});
</script>